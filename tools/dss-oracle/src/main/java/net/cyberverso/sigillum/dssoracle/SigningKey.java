package net.cyberverso.sigillum.dssoracle;

import eu.europa.esig.dss.enumerations.DigestAlgorithm;
import eu.europa.esig.dss.enumerations.EncryptionAlgorithm;
import eu.europa.esig.dss.enumerations.SignatureAlgorithm;
import eu.europa.esig.dss.model.SignatureValue;
import eu.europa.esig.dss.spi.DSSSecurityProvider;
import java.io.IOException;
import java.io.StringReader;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.MessageDigest;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.security.SecureRandom;
import java.security.Signature;
import java.security.interfaces.ECPrivateKey;
import java.security.interfaces.EdECPrivateKey;
import java.security.interfaces.RSAPrivateKey;
import java.security.spec.MGF1ParameterSpec;
import java.security.spec.PSSParameterSpec;
import org.bouncycastle.asn1.pkcs.PrivateKeyInfo;
import org.bouncycastle.openssl.jcajce.JcaPEMKeyConverter;
import org.bouncycastle.util.io.pem.PemObject;
import org.bouncycastle.util.io.pem.PemReader;

/**
 * The private key of a signer, read from a PKCS#8 file (OneAsymmetricKey, RFC 5958, section 2), and the
 * signature operation that DSS leaves to the caller. Every signature is
 * deterministic, so that the signed corpus can be regenerated byte for byte:
 * RSA PKCS#1 v1.5 and Ed25519 are deterministic by construction, ECDSA uses
 * the deterministic nonces of RFC 6979, and the RSASSA-PSS salt is derived
 * from the data to be signed. These are test keys, so a predictable salt
 * does no harm.
 */
final class SigningKey {

    /** The label of the derivation of RSASSA-PSS salts. */
    private static final byte[] SALT_LABEL = "sigillum dss-oracle RSASSA-PSS salt".getBytes(StandardCharsets.US_ASCII);

    private final PrivateKey key;

    private SigningKey(PrivateKey key) {
        this.key = key;
    }

    /**
     * Reads a private key from a PKCS#8 PEM block labelled {@code PRIVATE
     * KEY} (RFC 7468, section 10) or from DER.
     *
     * @param content the content of the file
     * @return the key
     * @throws IllegalArgumentException if the content is not a supported private key
     */
    static SigningKey read(byte[] content) {
        byte[] der = content;
        String text = new String(content, StandardCharsets.US_ASCII);
        if (text.contains("-----BEGIN ")) {
            try (PemReader reader = new PemReader(new StringReader(text))) {
                PemObject object = reader.readPemObject();
                if (object == null || !object.getType().equals("PRIVATE KEY")) {
                    throw new IllegalArgumentException("not a PKCS#8 PEM block labelled PRIVATE KEY");
                }
                der = object.getContent();
            } catch (IOException e) {
                throw new IllegalArgumentException("the PEM block cannot be read: " + e.getMessage(), e);
            }
        }
        try {
            PrivateKeyInfo info = PrivateKeyInfo.getInstance(der);
            if (info == null) {
                throw new IllegalArgumentException("the key is empty");
            }
            return new SigningKey(new JcaPEMKeyConverter().getPrivateKey(info));
        } catch (IOException | RuntimeException e) {
            throw new IllegalArgumentException("not a PKCS#8 private key: " + e.getMessage(), e);
        }
    }

    /**
     * Returns the algorithm used when none is requested: RSA PKCS#1 v1.5
     * with SHA-256 for RSA, ECDSA with the hash that RFC 5480, section 4,
     * pairs with the curve, and Ed25519.
     *
     * @return the algorithm
     * @throws IllegalArgumentException if the key type is not supported
     */
    SignatureAlgorithm defaultAlgorithm() {
        if (key instanceof RSAPrivateKey) {
            return SignatureAlgorithm.RSA_SHA256;
        }
        if (key instanceof ECPrivateKey ec) {
            int bits = ec.getParams().getCurve().getField().getFieldSize();
            return switch (bits) {
                case 256 -> SignatureAlgorithm.ECDSA_SHA256;
                case 384 -> SignatureAlgorithm.ECDSA_SHA384;
                case 521 -> SignatureAlgorithm.ECDSA_SHA512;
                default -> throw new IllegalArgumentException("elliptic curves of " + bits + " bits are not supported");
            };
        }
        if (isEd25519()) {
            return SignatureAlgorithm.ED25519;
        }
        throw new IllegalArgumentException("keys of type " + key.getAlgorithm() + " are not supported");
    }

    /**
     * Reports whether this key can sign with an algorithm.
     *
     * @param algorithm the algorithm
     * @return {@code true} if the key type fits the algorithm and the tool supports it
     */
    boolean fits(SignatureAlgorithm algorithm) {
        EncryptionAlgorithm encryption = algorithm.getEncryptionAlgorithm();
        if (algorithm.getDigestAlgorithm() == null) {
            return false;
        }
        return switch (encryption) {
            case RSA, RSASSA_PSS -> key instanceof RSAPrivateKey;
            case ECDSA -> key instanceof ECPrivateKey;
            case EDDSA -> algorithm == SignatureAlgorithm.ED25519 && isEd25519();
            default -> false;
        };
    }

    private boolean isEd25519() {
        if (key instanceof EdECPrivateKey edwards) {
            return edwards.getParams().getName().equalsIgnoreCase("Ed25519");
        }
        return key.getAlgorithm().equals("Ed25519");
    }

    /**
     * Signs data with an algorithm that {@link #fits(SignatureAlgorithm)}.
     *
     * @param algorithm the algorithm
     * @param data the data to be signed, as DSS gives it
     * @return the signature value
     * @throws GeneralSecurityException if the signature cannot be computed
     */
    SignatureValue sign(SignatureAlgorithm algorithm, byte[] data) throws GeneralSecurityException {
        Signature signature = engine(algorithm);
        if (algorithm.getEncryptionAlgorithm() == EncryptionAlgorithm.RSASSA_PSS) {
            signature.initSign(key, new DerivedRandom(data));
        } else {
            signature.initSign(key);
        }
        signature.update(data);
        return new SignatureValue(algorithm, signature.sign());
    }

    /**
     * Checks a signature value with a public key, as a check that the key
     * matches a certificate.
     *
     * @param algorithm the algorithm of the signature
     * @param publicKey the public key
     * @param data the signed data
     * @param value the signature value
     * @return {@code true} if the signature verifies
     * @throws GeneralSecurityException if the public key does not fit the algorithm
     */
    static boolean verify(SignatureAlgorithm algorithm, PublicKey publicKey, byte[] data, byte[] value)
            throws GeneralSecurityException {
        Signature signature = engine(algorithm);
        signature.initVerify(publicKey);
        signature.update(data);
        return signature.verify(value);
    }

    private static Signature engine(SignatureAlgorithm algorithm) throws GeneralSecurityException {
        DigestAlgorithm digest = algorithm.getDigestAlgorithm();
        return switch (algorithm.getEncryptionAlgorithm()) {
            case RSA -> Signature.getInstance(algorithm.getJCEId());
            case RSASSA_PSS -> {
                // RFC 8017, section 9.1, with MGF1 over the same hash and a salt as long as the hash,
                // as DSS encodes the parameters (RFC 4055, section 3.1).
                Signature pss = Signature.getInstance("RSASSA-PSS");
                pss.setParameter(new PSSParameterSpec(digest.getJavaName(), "MGF1",
                        new MGF1ParameterSpec(digest.getJavaName()), digest.getSaltLength(),
                        PSSParameterSpec.TRAILER_FIELD_BC));
                yield pss;
            }
            // RFC 6979: deterministic ECDSA, from the provider that DSS registers.
            case ECDSA -> Signature.getInstance(digest.getName() + "withECDDSA",
                    DSSSecurityProvider.getSecurityProvider());
            case EDDSA -> Signature.getInstance("Ed25519");
            default -> throw new GeneralSecurityException("unsupported algorithm " + algorithm);
        };
    }

    /**
     * A source of salt bytes derived from the data to be signed: SHA-256 in
     * counter mode over a fixed label and the data.
     */
    private static final class DerivedRandom extends SecureRandom {
        private static final long serialVersionUID = 1L;

        private final byte[] seed;
        private long counter;

        DerivedRandom(byte[] data) {
            this.seed = data.clone();
        }

        @Override
        public void nextBytes(byte[] bytes) {
            int filled = 0;
            while (filled < bytes.length) {
                MessageDigest sha256;
                try {
                    sha256 = MessageDigest.getInstance("SHA-256");
                } catch (GeneralSecurityException e) {
                    throw new IllegalStateException(e);
                }
                sha256.update(SALT_LABEL);
                sha256.update(seed);
                sha256.update(ByteBuffer.allocate(Long.BYTES).putLong(counter++).array());
                byte[] block = sha256.digest();
                int length = Math.min(block.length, bytes.length - filled);
                System.arraycopy(block, 0, bytes, filled, length);
                filled += length;
            }
        }
    }
}
